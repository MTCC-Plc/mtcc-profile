// Regenerates app/assets/registry.ts from whatever images are in app/assets.
//
// Run after adding or removing an image:
//   node scripts/generate-image-registry.mjs
//
// Replacing an image does not need this — the filename stays the same and Next
// re-hashes the output on the next build.

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const assets = join(root, "app", "assets");
const extensions = new Set([".webp", ".png", ".svg", ".jpg", ".jpeg", ".avif", ".gif"]);

function walk(dir) {
  return readdirSync(dir).flatMap(entry => {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) return walk(full);
    const dot = entry.lastIndexOf(".");
    return dot > 0 && extensions.has(entry.slice(dot).toLowerCase()) ? [full] : [];
  });
}

const files = walk(assets)
  .map(f => relative(assets, f).split("\\").join("/"))
  .sort();

const used = new Map();
for (const rel of files) {
  const base = rel.replace(/\.[^.]+$/, "").replace(/[^0-9a-zA-Z]+/g, "_");
  let name = /^\d/.test(base) ? `_${base}` : base;
  for (let i = 2; used.has(name); i++) name = `${base}_${i}`;
  used.set(name, rel);
}

const header = `// Generated by scripts/generate-image-registry.mjs — do not edit by hand.
//
// Importing images as modules puts them through the Next.js asset pipeline, so
// each file is emitted with a content hash in its name. Replacing a picture
// changes its URL automatically, which is what stops browsers serving a stale
// copy — the problem manual filenames in public/ kept causing.
//
// Keys are the original public paths, so existing "/assets/..." strings in data
// and components keep working: SiteImage resolves them through this map.
`;

const body = [
  header,
  'import type { StaticImageData } from "next/image";',
  "",
  ...[...used].map(([name, rel]) => `import ${name} from "./${rel}";`),
  "",
  "export const imageRegistry: Record<string, StaticImageData> = {",
  ...[...used].map(([name, rel]) => `  "/assets/${rel}": ${name},`),
  "};",
  "",
].join("\n");

writeFileSync(join(assets, "registry.ts"), body);
console.log(`registry.ts written with ${used.size} images`);
